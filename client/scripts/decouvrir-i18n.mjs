// Version française : pas de redirection automatique dans les versions traduites
const REDIRECT_START = '<!-- redirection-langue -->';
const REDIRECT_END = '<!-- /redirection-langue -->';
for (const [lang, pairs] of Object.entries(T)) {
  let out = src;
  const i = out.indexOf(REDIRECT_START), j = out.indexOf(REDIRECT_END);
  if (i < 0 || j < 0) throw new Error('Bloc de redirection introuvable dans decouvrir.html');
  out = out.slice(0, i) + out.slice(j + REDIRECT_END.length);
  for (const [fr, tr] of pairs) {
    if (!out.includes(fr)) throw new Error(`[${lang}] introuvable : ${fr.slice(0, 70)}`);
    out = out.split(fr).join(tr);
  }
  out = out.replace('data-lang="fr" aria-current="true"', 'data-lang="fr"').replace(`data-lang="${lang}"`, `data-lang="${lang}" aria-current="true"`);
  writeFileSync(new URL(`../public/decouvrir-${lang}.html`, import.meta.url), out);
  console.log(`decouvrir-${lang}.html`);
}
